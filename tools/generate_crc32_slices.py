"""Regenerate the portable IEEE CRC-32 slicing tables (no ROM input)."""
from pathlib import Path

tables = []
for row in range(8):
    table = []
    for byte in range(256):
        crc = byte if row == 0 else tables[row - 1][byte]
        for _ in range(8):
            crc = (crc >> 1) ^ (0xedb88320 if crc & 1 else 0)
        table.append(crc)
    tables.append(table)
lines = ['/* Generated by tools/generate_crc32_slices.py; IEEE reflected polynomial. */',
         'static const uint32_t s_slices[8][256] = {']
for table in tables:
    lines.append('  {')
    for offset in range(0, 256, 8):
        lines.append('    ' + ', '.join(f'0x{value:08x}u' for value in table[offset:offset+8]) + ',')
    lines.append('  },')
lines.append('};')
(Path(__file__).resolve().parents[1]/'runner/src/crc32_slices.inc').write_bytes(('\n'.join(lines)+'\n').encode('ascii'))
